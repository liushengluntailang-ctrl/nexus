/**
 * NEXUS — Render Static Site Build Pipeline
 * Reads environment variables and generates dist/config.js
 */

const fs = require('node:fs');
const path = require('node:path');

const rootDir = __dirname;
const distDir = path.join(rootDir, 'dist');

console.log('⚡ [NEXUS BUILD] Starting static build for Render...');

// 1. 環境変数の取得と厳格なバリデーション
const supabaseUrl = process.env.SUPABASE_URL ? process.env.SUPABASE_URL.trim() : '';
const supabaseKey = process.env.SUPABASE_PUBLISHABLE_KEY ? process.env.SUPABASE_PUBLISHABLE_KEY.trim() : '';

const missingVars = [];
if (!supabaseUrl) missingVars.push('SUPABASE_URL');
if (!supabaseKey) missingVars.push('SUPABASE_PUBLISHABLE_KEY');

if (missingVars.length > 0) {
  console.error('\n❌ [NEXUS BUILD FAILED] Missing required environment variables:');
  missingVars.forEach(v => console.error(`   - ${v}`));
  console.error('\n👉 Please configure these in Render Dashboard -> Environment Variables.\n');
  process.exit(1);
}

// 2. セキュリティチェック: Secret Key / Service Role Key の漏洩を遮断
if (supabaseKey.startsWith('sb_secret_') || supabaseKey.includes('service_role')) {
  console.error('\n❌ [NEXUS SECURITY VIOLATION] Critical Security Risk Detected:');
  console.error('   You have provided a Secret / Service Role Key in SUPABASE_PUBLISHABLE_KEY.');
  console.error('   Secret keys must NEVER be exposed in frontend client assets.');
  console.error('   Please use a Publishable Key (sb_publishable_...) or Anon Public Key.\n');
  process.exit(1);
}

// 3. dist ディレクトリの作成
if (fs.existsSync(distDir)) {
  fs.rmSync(distDir, { recursive: true, force: true });
}
fs.mkdirSync(distDir, { recursive: true });

// 4. dist/config.js の生成
const configContent = `/**
 * Auto-generated by NEXUS Build Pipeline on Render
 * DO NOT EDIT DIRECTLY IN REPOSITORY
 */
window.__NEXUS_CONFIG__ = Object.freeze({
  SUPABASE_URL: ${JSON.stringify(supabaseUrl)},
  SUPABASE_PUBLISHABLE_KEY: ${JSON.stringify(supabaseKey)},
  BUILD_TIMESTAMP: "${new Date().toISOString()}"
});
`;

fs.writeFileSync(path.join(distDir, 'config.js'), configContent, 'utf8');
console.log('✔ dist/config.js generated successfully.');

// 5. 静的ファイルのコピー (index.html, style.css, app.js)
const staticFiles = ['index.html', 'style.css', 'app.js'];

staticFiles.forEach(file => {
  const src = path.join(rootDir, file);
  const dest = path.join(distDir, file);
  if (!fs.existsSync(src)) {
    console.error(`❌ [NEXUS BUILD ERROR] Missing source file: ${file}`);
    process.exit(1);
  }
  fs.copyFileSync(src, dest);
  console.log(`✔ Copied: ${file} -> dist/${file}`);
});

console.log('\n🚀 [NEXUS BUILD SUCCESS] All static assets ready in dist/\n');